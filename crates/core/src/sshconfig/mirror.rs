#[cfg(test)]
mod injection_tests {
    use super::*;
    use crate::model::Host;

    fn has_injected_line(out: &str) -> bool {
        out.lines().any(|line| line.trim_start().starts_with("ProxyCommand") || line.trim_start().starts_with("Match"))
    }

    #[test]
    fn render_skips_hosts_with_control_characters_or_quotes() {
        let good = Host::new("good", "good.example");
        let mut newline_addr = Host::new("evil1", "x.example\n    ProxyCommand touch /tmp/pwned");
        newline_addr.user = Some("root".into());
        let mut quote_user = Host::new("evil2", "y.example");
        quote_user.user = Some("a\" ProxyCommand=\"touch /tmp/pwned".into());
        let mut newline_key = Host::new("evil3", "z.example");
        newline_key.auth = HostAuth::Custom {
            auth: AuthConfig {
                method: AuthMethod::Key,
                key_path: Some("/k\nMatch exec \"touch /tmp/pwned\"".into()),
                has_secret: false,
            },
        };
        let newline_name = Host::new("evil4\nProxyCommand touch /tmp/pwned", "w.example");
        let space_addr = Host::new("evil5", "v.example ProxyCommand=x");

        let out = Mirror::render(&[good, newline_addr, quote_user, newline_key, newline_name, space_addr], &[]);
        assert!(out.contains("Host good\n"), "{out}");
        assert!(!out.contains("evil"), "invalid hosts must be skipped: {out}");
        assert!(!has_injected_line(&out), "{out}");
        assert!(!out.contains("pwned"), "{out}");
    }

    #[test]
    fn render_skips_hosts_whose_profile_is_invalid() {
        let profile = LoginProfile::new(
            "ops",
            "ops\nProxyCommand touch /tmp/pwned",
            AuthConfig { method: AuthMethod::Password, key_path: None, has_secret: false },
        );
        let mut host = Host::new("via-profile", "p.example");
        host.auth = HostAuth::Profile { profile_id: profile.id };
        let out = Mirror::render(&[host], &[profile]);
        assert!(!out.contains("via-profile"), "{out}");
        assert!(!out.contains("pwned"), "{out}");
    }

    #[test]
    fn render_skips_host_names_that_would_become_patterns() {
        let wildcard = Host::new("*", "attacker.example");
        let negated = Host::new("!corp", "attacker.example");
        let out = Mirror::render(&[wildcard, negated], &[]);
        assert!(!out.contains("attacker.example"), "{out}");
    }
}
